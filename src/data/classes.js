export function spellSlots(cls, level) {
  if (!cls || !cls.caster) return null;
  if (cls.caster === 'pact') {
    const [n, lvl] = PACT[level - 1];
    return { pact: true, count: n, level: lvl };
  }
  let eff = level;
  if (cls.caster === 'half') eff = level < 2 ? 0 : Math.floor(level / 2);
  if (cls.caster === 'artificer') eff = Math.ceil(level / 2);
  if (cls.caster === 'third') eff = level < 3 ? 0 : Math.floor(level / 3);
  if (eff <= 0) return { slots: [] };
  return { slots: FULL[eff - 1] };
}

